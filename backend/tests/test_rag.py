@pytest.mark.asyncio
async def test_document_and_collection_scope_validation(test_db_session: AsyncSession):
    """Regression Test: Scoping inquiry to a specific document or collection is strictly enforced."""
    async def override_get_db():
        yield test_db_session

    app.dependency_overrides[get_db] = override_get_db
    transport = ASGITransport(app=app)

    async with AsyncClient(transport=transport, base_url="http://testserver") as client:
        reg_res = await client.post("/api/v1/auth/register", json={
            "email": "scoping_test@lab.org",
            "password": "Password123!",
            "full_name": "Scoping Researcher",
        })
        user_id = reg_res.json()["id"]

        # Doc 1: Renewable
        doc_ren = Document(
            user_id=user_id,
            filename="clean_power.pdf",
            storage_path="backend/storage/documents/clean_power.pdf",
            file_size_bytes=1000,
            mime_type="application/pdf",
            page_count=2,
            processing_status="READY",
        )
        # Doc 2: Robotics
        doc_robotics = Document(
            user_id=user_id,
            filename="robotics.pdf",
            storage_path="backend/storage/documents/robotics.pdf",
            file_size_bytes=1000,
            mime_type="application/pdf",
            page_count=2,
            processing_status="READY",
        )
        test_db_session.add_all([doc_ren, doc_robotics])
        await test_db_session.flush()

        emb_ren = await embedding_service.embed_query("Solar, wind, and hydro are renewable energies.")
        emb_rob = await embedding_service.embed_query("Inverse kinematics for robotic arms.")

        chunk_ren = DocumentChunk(
            document_id=doc_ren.id,
            user_id=user_id,
            chunk_index=0,
            page_number=1,
            content="Solar, wind, and hydro are renewable energies.",
            token_count=15,
            embedding=emb_ren,
        )
        chunk_rob = DocumentChunk(
            document_id=doc_robotics.id,
            user_id=user_id,
            chunk_index=0,
            page_number=1,
            content="Inverse kinematics for robotic arms.",
            token_count=15,
            embedding=emb_rob,
        )
        test_db_session.add_all([chunk_ren, chunk_rob])

        # Collection containing only robotics
        col = Collection(user_id=user_id, name="Robotics Collection")
        test_db_session.add(col)
        await test_db_session.flush()

        col_doc = CollectionDocument(collection_id=col.id, document_id=doc_robotics.id)
        test_db_session.add(col_doc)
        await test_db_session.commit()

        # Querying renewable energy when scoped to robotics document -> insufficient evidence
        scoped_doc_res = await client.post("/api/v1/chat/ask", json={
            "question": "What are three examples of renewable energy?",
            "document_id": doc_robotics.id,
        })
        assert scoped_doc_res.status_code == 200
        assert INSUFFICIENT_EVIDENCE_ANSWER in scoped_doc_res.json()["assistant_message"]["content"]
        assert len(scoped_doc_res.json()["assistant_message"]["citations"]) == 0

        # Querying renewable energy when scoped to robotics collection -> insufficient evidence
        scoped_col_res = await client.post("/api/v1/chat/ask", json={
            "question": "What are three examples of renewable energy?",
            "collection_id": col.id,
        })
        assert scoped_col_res.status_code == 200
        assert INSUFFICIENT_EVIDENCE_ANSWER in scoped_col_res.json()["assistant_message"]["content"]
        assert len(scoped_col_res.json()["assistant_message"]["citations"]) == 0

        # Querying with document not in the collection -> 400 Bad Request
        mismatch_res = await client.post("/api/v1/chat/ask", json={
            "question": "What are three examples of renewable energy?",
            "document_id": doc_ren.id,
            "collection_id": col.id,
        })
        assert mismatch_res.status_code == 400
        assert "does not belong to the selected collection" in mismatch_res.json()["detail"]

    app.dependency_overrides.clear()
