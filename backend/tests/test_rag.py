    """Verify CSRF token enforcement on state-changing chat requests."""
    # Temporarily set environment to production to verify strict CSRF enforcement
    monkeypatch.setattr(settings, "ENVIRONMENT", "production")

    async def override_get_db():
        yield test_db_session

    app.dependency_overrides[get_db] = override_get_db
    transport = ASGITransport(app=app)

    async with AsyncClient(transport=transport, base_url="http://testserver") as client:
        # Register user (sets session cookie)
        reg_res = await client.post("/api/v1/auth/register", json={
            "email": "csrf_test@security.org",
            "password": "Password123!",
            "full_name": "CSRF User",
        })
        assert reg_res.status_code == 201
        user_id = reg_res.json()["id"]

        # 1. State-changing request without CSRF token in production -> 403 Forbidden
        no_csrf_res = await client.post("/api/v1/chat/conversations", json={
            "title": "Unprotected Request",
        })
        assert no_csrf_res.status_code == 403
        assert "CSRF token" in no_csrf_res.json()["detail"]

        # 2. State-changing request with invalid CSRF token -> 403 Forbidden
        bad_csrf_res = await client.post(
            "/api/v1/chat/conversations",
            json={"title": "Bad CSRF Request"},
            headers={"X-CSRF-Token": "invalid.csrf.token"},
        )
        assert bad_csrf_res.status_code == 403

        # 3. State-changing request with valid CSRF token -> 201 Created
        valid_csrf = generate_csrf_token(user_id)
        good_res = await client.post(
            "/api/v1/chat/conversations",
            json={"title": "Protected Valid Request"},
            headers={"X-CSRF-Token": valid_csrf},
        )
        assert good_res.status_code == 201
        assert good_res.json()["title"] == "Protected Valid Request"

    app.dependency_overrides.clear()


