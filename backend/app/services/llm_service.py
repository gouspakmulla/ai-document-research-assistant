import abc
import asyncio
import re
from typing import Optional, List, Dict, Any
import httpx
from backend.app.core.config import settings


class BaseLLMProvider(abc.ABC):
    """Abstract base provider for Large Language Model text generation."""

    @abc.abstractmethod
    async def generate_response(
        self,
        system_prompt: str,
        user_prompt: str,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> str:
        """Generate an answer string based on system prompt and user prompt."""
        pass


class MockLLMProvider(BaseLLMProvider):
    """Deterministic, zero-cost LLM provider for offline development and automated testing.

    Strictly synthesizes grounded answers using only the provided context chunks.
    Identifies itself clearly in every response to prevent deceptive presentation.
    """

    MOCK_HEADER = "[Mock AI Response]"
    MOCK_FOOTER = "*(Generated by Mock AI Provider for offline testing)*"

    async def generate_response(
        self,
        system_prompt: str,
        user_prompt: str,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> str:
        # Check if context contains chunks
        # Extract sources from prompt: looking for <source id="(\d+)" chunk_id="([^"]+)" doc="([^"]+)" page="(\d+)">
        sources: List[Dict[str, str]] = []
        source_pattern = re.compile(
            r'<source\s+id="(?P<id>\d+)"\s+chunk_id="(?P<chunk_id>[^"]+)"\s+doc="(?P<doc>[^"]+)"\s+page="(?P<page>\d+)"[^>]*>(?P<content>.*?)</source>',
            re.DOTALL | re.IGNORECASE,
        )
        for m in source_pattern.finditer(user_prompt):
            sources.append({
                "id": m.group("id"),
                "chunk_id": m.group("chunk_id"),
                "doc": m.group("doc"),
                "page": m.group("page"),
                "content": m.group("content").strip(),
            })

        # If no sources in prompt or prompt indicates no evidence
        if not sources or "NO_RETRIEVED_CHUNKS" in user_prompt:
            return (
                f"{self.MOCK_HEADER} I do not have sufficient evidence in the uploaded documents "
                f"to answer this question.\n\n{self.MOCK_FOOTER}"
            )

        # Check for prompt injection attempts in the content or question
        injection_triggers = [
            "ignore previous instructions",
            "ignore all previous",
            "system prompt",
            "override rules",
            "system override",
            "disclose secret",
            "exfiltrate",
            "admin_password",
            "admin password",
            "jailbreak",
        ]
        has_injection = any(t in user_prompt.lower() for t in injection_triggers)

        # Synthesize deterministic answer based on actual sources
        findings: List[str] = []
        for s in sources:
            raw_content = s["content"].replace("\n", " ").strip()
            # If chunk contains injection commands, neutralize them
            sanitized_chunk = raw_content
            for trigger in injection_triggers:
                if trigger in sanitized_chunk.lower():
                    pattern = re.compile(re.escape(trigger) + r"[^\.\,\;\n]*", re.IGNORECASE)
                    sanitized_chunk = pattern.sub("[Neutralized untrusted instruction]", sanitized_chunk)

            if len(sanitized_chunk) > 120:
                sanitized_chunk = sanitized_chunk[:120].rstrip() + "..."
            findings.append(
                f"- According to **{s['doc']}** (Page {s['page']}) [Source {s['id']}]: \"{sanitized_chunk}\""
            )

        findings_text = "\n".join(findings)

        if has_injection:
            body = (
                f"I processed your query against the verified document evidence while enforcing system safety rules. "
                f"Document content is treated as untrusted data and instructions to override system behavior have been ignored.\n\n"
                f"Document evidence retrieved:\n{findings_text}"
            )
        else:
            body = (
                f"Based on the verified document evidence, here are the findings relevant to your inquiry:\n\n"
                f"{findings_text}\n\n"
                f"All statements above are directly supported by the retrieved document chunks."
            )

        return f"{self.MOCK_HEADER} {body}\n\n{self.MOCK_FOOTER}"


class OpenAILLMProvider(BaseLLMProvider):
    """OpenAI Chat Completions API provider with timeouts and exponential backoff."""

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: str = settings.LLM_MODEL,
        temperature: float = settings.LLM_TEMPERATURE,
        max_tokens: int = settings.LLM_MAX_TOKENS,
        max_retries: int = 3,
        timeout_seconds: float = 30.0,
    ):
        self.api_key = api_key or settings.OPENAI_API_KEY
        if not self.api_key:
            raise ValueError(
                "OPENAI_API_KEY is not configured for OpenAI LLM provider. "
                "Please set OPENAI_API_KEY in your environment or set LLM_PROVIDER=mock."
            )
        self.model = model
        self.temperature = temperature
        self.max_tokens = max_tokens
        self.max_retries = max_retries
        self.timeout = timeout_seconds

    async def generate_response(
        self,
        system_prompt: str,
        user_prompt: str,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> str:
        url = "https://api.openai.com/v1/chat/completions"
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }
        payload: Dict[str, Any] = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            "temperature": temperature if temperature is not None else self.temperature,
            "max_tokens": max_tokens if max_tokens is not None else self.max_tokens,
        }

        async with httpx.AsyncClient(timeout=self.timeout) as client:
            for attempt in range(self.max_retries):
                try:
                    resp = await client.post(url, json=payload, headers=headers)
                    if resp.status_code == 200:
                        data = resp.json()
                        choices = data.get("choices", [])
                        if not choices:
                            raise RuntimeError("OpenAI returned empty completion choices.")
                        return choices[0]["message"]["content"].strip()
                    elif resp.status_code == 429:
                        # Rate limit
                        retry_after = 2**attempt + 0.5
                        if attempt < self.max_retries - 1:
                            await asyncio.sleep(retry_after)
                            continue
                        raise RuntimeError("OpenAI rate limit exceeded. Please try again shortly.")
                    elif resp.status_code in (500, 502, 503, 504):
                        if attempt < self.max_retries - 1:
                            await asyncio.sleep(2**attempt + 0.5)
                            continue
                        raise RuntimeError(f"OpenAI service unavailable (HTTP {resp.status_code}).")
                    else:
                        err_text = resp.text
                        raise RuntimeError(f"OpenAI API error {resp.status_code}: {err_text}")
                except (httpx.TimeoutException, httpx.NetworkError) as e:
                    if attempt < self.max_retries - 1:
                        await asyncio.sleep(2**attempt + 0.5)
                        continue
                    raise RuntimeError(f"OpenAI connection failed after {self.max_retries} attempts: {e}") from e

        raise RuntimeError("OpenAI generation failed.")


class GeminiLLMProvider(BaseLLMProvider):
    """Google Gemini LLM provider using Google Generative AI REST endpoint."""

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: str = "gemini-1.5-flash",
        temperature: float = settings.LLM_TEMPERATURE,
        max_tokens: int = settings.LLM_MAX_TOKENS,
        max_retries: int = 3,
        timeout_seconds: float = 30.0,
    ):
        self.api_key = api_key or settings.GEMINI_API_KEY
        if not self.api_key:
            raise ValueError(
                "GEMINI_API_KEY is not configured for Gemini LLM provider. "
                "Please set GEMINI_API_KEY in your environment or set LLM_PROVIDER=mock."
            )
        self.model = model
        self.temperature = temperature
        self.max_tokens = max_tokens
        self.max_retries = max_retries
        self.timeout = timeout_seconds

    async def generate_response(
        self,
        system_prompt: str,
        user_prompt: str,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> str:
        url = (
            f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent"
            f"?key={self.api_key}"
        )
        payload = {
            "systemInstruction": {
                "parts": [{"text": system_prompt}]
            },
            "contents": [
                {
                    "role": "user",
                    "parts": [{"text": user_prompt}]
                }
            ],
            "generationConfig": {
                "temperature": temperature if temperature is not None else self.temperature,
                "maxOutputTokens": max_tokens if max_tokens is not None else self.max_tokens,
            },
        }

        async with httpx.AsyncClient(timeout=self.timeout) as client:
            for attempt in range(self.max_retries):
                try:
                    resp = await client.post(url, json=payload)
                    if resp.status_code == 200:
                        data = resp.json()
                        candidates = data.get("candidates", [])
                        if not candidates:
                            raise RuntimeError("Gemini returned empty completion candidates.")
                        parts = candidates[0].get("content", {}).get("parts", [])
                        if not parts:
                            raise RuntimeError("Gemini returned empty content parts.")
                        return parts[0].get("text", "").strip()
                    elif resp.status_code in (429, 500, 502, 503, 504):
                        if attempt < self.max_retries - 1:
                            await asyncio.sleep(2**attempt + 0.5)
                            continue
                        raise RuntimeError(f"Gemini API returned status {resp.status_code}.")
                    else:
                        raise RuntimeError(f"Gemini API error {resp.status_code}: {resp.text}")
                except (httpx.TimeoutException, httpx.NetworkError) as e:
                    if attempt < self.max_retries - 1:
                        await asyncio.sleep(2**attempt + 0.5)
                        continue
                    raise RuntimeError(f"Gemini connection error: {e}") from e

        raise RuntimeError("Gemini generation failed.")


def get_llm_provider(provider_name: Optional[str] = None) -> BaseLLMProvider:
    """Factory to retrieve configured LLM provider with explicit configuration validation.

    Never silently falls back to Mock provider when a real provider is explicitly requested.
    """
    provider = (provider_name or settings.LLM_PROVIDER).lower().strip()

    if provider == "mock":
        return MockLLMProvider()

    if provider == "openai":
        if not settings.OPENAI_API_KEY:
            raise ValueError(
                "LLM_PROVIDER is configured as 'openai', but OPENAI_API_KEY is not set. "
                "Please configure OPENAI_API_KEY in your environment or set LLM_PROVIDER=mock."
            )
        return OpenAILLMProvider()

    if provider == "gemini":
        if not settings.GEMINI_API_KEY:
            raise ValueError(
                "LLM_PROVIDER is configured as 'gemini', but GEMINI_API_KEY is not set. "
                "Please configure GEMINI_API_KEY in your environment or set LLM_PROVIDER=mock."
            )
        return GeminiLLMProvider()

    raise ValueError(
        f"Unknown LLM_PROVIDER '{provider}'. Supported providers are 'mock', 'openai', and 'gemini'."
    )
